def test_the_script_never_generates_narrative() -> None:
    """The boundary: no section body may be synthesised from collected data."""
    source = SCRIPT.read_text(encoding="utf-8")
    assert "--input" in source
    for forbidden in ('["git"', "collect_repo_state", "def generate_"):
        assert forbidden not in source, f"{forbidden!r} crosses the prose boundary"
    # Every section body originates in --input: compose_guide reads only *data*.
    compose = source[
        source.index("def compose_guide") : source.index("def validate_guide")
    ]
    assert "data.get(section.key)" in compose
    assert "root" not in compose and "read_text" not in compose


# --- Writer Safety -----------------------------------------------------------


def test_the_hash_guard_refuses_a_guide_changed_since_load(
    project: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    guide = project / "GUIDE.md"
    guide.write_text("# Project Guide\n\nold\n", encoding="utf-8")
    real_read_text = Path.read_text
    real_write_text = Path.write_text
    reads = {"n": 0}

    def counting_read_text(self: Path, *args: object, **kwargs: object) -> str:
        if self.name == "GUIDE.md":
            reads["n"] += 1
            if reads["n"] == 1:
                text = real_read_text(self, *args, **kwargs)  # type: ignore[arg-type]
                real_write_text(self, text + "\nconcurrent note\n")  # type: ignore[arg-type]
                return text
        return real_read_text(self, *args, **kwargs)  # type: ignore[arg-type,return-value]

    monkeypatch.setattr(Path, "read_text", counting_read_text)
    monkeypatch.setattr(
        sys,
        "argv",
        [
            "write_guide.py",
            "--project-root",
            str(project),
            "--input",
            str(write_input(project, BODY)),
            "--apply",
        ],
    )

    assert wg.main() == 3
    text = real_read_text(guide)  # type: ignore[arg-type]
    assert "concurrent note" in text, "the concurrent write must survive"
    assert "Shared agent contract" not in text, "our write must not have landed"


def test_validation_runs_before_the_replace_and_leaves_no_temp_file(
    project: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    guide = project / "GUIDE.md"
    guide.write_text("# Project Guide\n\nold\n", encoding="utf-8")
    calls = {"n": 0}

    def failing_second_validation(text: str, project_root: Path) -> str | None:
        calls["n"] += 1
        return "injected structural damage" if calls["n"] == 2 else None

    monkeypatch.setattr(wg, "validate_guide_document", failing_second_validation)
    monkeypatch.setattr(
        sys,
        "argv",
        [
            "write_guide.py",
            "--project-root",
            str(project),
            "--input",
            str(write_input(project, BODY)),
            "--apply",
        ],
    )

    assert wg.main() == 2
    assert guide.read_text(encoding="utf-8") == "# Project Guide\n\nold\n"
    assert list(project.glob(".GUIDE.md-*")) == []


